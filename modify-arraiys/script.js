let shoppingList = [ 'Cheddar Cheese', '2% Milk '];

shoppingList[1] = 'Almond Milk';
shoppingList[2] = 'Canned Mushrooms';
// add items to list using length
shoppingList[shoppingList.length] = 'Tomatoes';
shoppingList[shoppingList.length] = 'Dark Chocolate';
shoppingList[shoppingList.length] = 'Tuna Salad';
// add to beginning of list [0] 
shoppingList[0] = "Whole Wheat Bread";
