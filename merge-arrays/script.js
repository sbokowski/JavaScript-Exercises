// Exercise 
//  Concat - merge arrays
// In JavaScript, concat is an array method
// used to combine merge 2 or more arrays
// into one new aray.
//
//
// It is usefull  when you want to join
// arrays toether without changing the
// original arrays.
// 
// 1. Basic concat() example
let fruits = ['pears', 'apricots'];
let vegetables = ['carrot', 'beans'];
// combine all food items into one
let food = fruits.concat(vegetables);

console.log(food);

// combine more than 2 arrays
let a = [1, 2, 3];
let b = [4, 5, 6];
let c = [7, 8, 9];

let numbers = a.concat(b, c);

console.log(numbers);
