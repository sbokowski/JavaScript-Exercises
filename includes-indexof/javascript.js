// In  Jasvascript indexOf() method is used to find the
//  position (index number) of a value inside a String
//  or an Array.
//
// It tells you where something is located.
// 
// There are two common ways to use. it.
// 1 indexOf()  with strings.
// 2 indexOf() with arrays.
// Example

// using indexOf() with strings

let message = "Will will broadcast tomorrow.";

console.log(message.indexOf("broacast"));

// Using indexOF() with arrays

let fruits = ['pears', 'apples', 'orange', 'strawberry'];

console.log(fruits.indexOf('orange'));
