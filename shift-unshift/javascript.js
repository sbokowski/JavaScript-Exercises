// Exercise
//  Shift and Unshift
// In JavaScript, shift() and unshift() are array
//  methods used to add or remove items at the beginning
// of an array.

// They are opposites of each other.
// 
// Push - add to end
// Pop -remove from  end
// Shift -remove from start
//  Unshift - add one more elements
let colors = ['red', 'blue' , 'green', 'black' , 'yellow'];
colors.shift(1);
console.log(colors);

